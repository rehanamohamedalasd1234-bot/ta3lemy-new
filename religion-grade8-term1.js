        if (record.updatedAt) row.appendChild(el('div', 'آخر تحديث: ' + new Date(record.updatedAt).toLocaleString('ar-EG')));
        if (record.sourceId) { var reopen = el('button', 'فتح مصدر السؤال لتعديل الدرجة'); reopen.type = 'button'; reopen.style.cssText = 'margin-top:8px;padding:8px 12px;background:#1565C0;color:white;border:0;border-radius:8px;font:inherit;cursor:pointer;'; reopen.addEventListener('click', function () { openItem(record.sourceId); }); row.appendChild(reopen); }
