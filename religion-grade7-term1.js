      example.appendChild(el('strong', 'تطبيق: '));
      example.appendChild(el('span', found.item.example));
      body.appendChild(example);
      var summary = el('div', undefined, 'religion-key');
      summary.style.cssText = 'background:#E3F2FD;border-radius:12px;padding:13px;margin:14px 0;line-height:1.9;';
      summary.appendChild(el('strong', 'خلاصة الدرس: '));
